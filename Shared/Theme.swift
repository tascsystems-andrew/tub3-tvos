    public static let gold = Color(red: 1.0, green: 0.784, blue: 0.235)
    public static let purple = Color(red: 0.659, green: 0.361, blue: 0.965)
    public static let dim = Color(red: 0.541, green: 0.514, blue: 0.471)
}
